#!/usr/bin/env bash
# Builds the DeziroJoy .rpm from a self-contained publish output.
#
# Usage:
#   tools/Packaging/linux/rpm/build-rpm.sh <version> <rid> <publish-dir> <output-dir>
#
# Payload layout (mirrors the .deb built by ../build-deb.sh one for one):
#   /opt/dezirojoy/                        the complete self-contained publish output
#   /opt/dezirojoy/dezirojoy.ico           application icon, kept for compatibility
#   /opt/dezirojoy/fix-device-access.sh    the opt-in device-access fix helper; the app
#                                          runs it through pkexec when the user asks for
#                                          the fix, never at install time
#   /usr/share/applications/dezirojoy.desktop
#   /usr/share/icons/hicolor/<size>/apps/dezirojoy.png
#                                           one PNG per hicolor size (16/24/32/48/64/
#                                           128/256), the .ico's own PNG frames committed
#                                           under src/DeziroJoy.App/Assets/ and installed
#                                           as-is; this is what the desktop entry's
#                                           Icon=dezirojoy theme name resolves against
#
# The package deliberately ships no scriptlets, no systemd units, no cron jobs
# and no udev rules: login autostart and the elevated resident daemon stay opt-in
# features of the app itself (src/DeziroJoy.App/Program.cs), and the user's
# configuration under ~/.config/DeziroJoy is never touched.
#
# Requires is generated by rpmbuild from the shipped binaries' DT_NEEDED
# sonames (find-requires); the .deb's Depends line is Debian package names and
# is deliberately not reused. ICU is dlopen'd by the runtime rather than linked,
# so the spec adds one explicit soname-based Requires for it - see
# dezirojoy.spec.
#
# Version: RPM forbids '-' in the Version field (it separates version from
# release), so '0.0.1-beta.5-preview' is sanitised to '0.0.1~beta.5~preview'
# and a plain '0.0.1' is unchanged. '~' sorts below every other character in
# rpm's version comparison, which reproduces semver prerelease ordering for
# free (0.0.1~beta.5~preview < 0.0.1). The release asset keeps the original
# semver version and drops rpm's release segment: DeziroJoy-<ver>-<arch>.rpm
# (x86_64 | aarch64). dnf installs a local file by name, so the NEVRA release
# segment is not needed in the file name.

set -euo pipefail

if [ "$#" -ne 4 ]; then
  echo "usage: $0 <version> <rid> <publish-dir> <output-dir>" >&2
  exit 2
fi

version="$1"
rid="$2"
publish="$3"
outdir="$4"

case "$rid" in
  linux-x64)   arch=x86_64 ;;
  linux-arm64) arch=aarch64 ;;
  *)
    echo "unsupported rid: $rid (expected linux-x64 or linux-arm64)" >&2
    exit 2
    ;;
esac

if [ -z "$version" ]; then
  echo "version must not be empty" >&2
  exit 2
fi
if [ ! -d "$publish" ]; then
  echo "publish directory not found: $publish" >&2
  exit 2
fi

exe="$publish/DeziroJoy"
if [ ! -f "$exe" ]; then
  echo "DeziroJoy binary missing from publish output: $exe" >&2
  exit 2
fi

# '-' is the version/release separator in RPM and cannot appear in Version.
# The replacement must stay escaped: an unescaped '~' in the substitution
# would be tilde-expanded to $HOME.
rpm_version="${version//-/\~}"

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$script_dir/../../../.." && pwd)"
icon="$repo_root/src/DeziroJoy.App/Assets/dezirojoy.ico"
desktop="$repo_root/tools/Packaging/linux/dezirojoy.desktop"
helper="$repo_root/tools/Packaging/linux/fix-device-access.sh"
spec="$script_dir/dezirojoy.spec"
for required in "$icon" "$desktop" "$helper" "$spec"; do
  if [ ! -f "$required" ]; then
    echo "required file missing: $required" >&2
    exit 2
  fi
done

stage="$(mktemp -d)"
topdir="$(mktemp -d)"
trap 'rm -rf "$stage" "$topdir"' EXIT

mkdir -p "$stage/opt/dezirojoy" "$stage/usr/share/applications"

# The complete publish output, PDBs included: crash reports need the symbols,
# and nothing is trimmed. The spec disables rpm's strip/debuginfo
# post-processing so the payload stays byte-for-byte as published.
cp -a "$publish/." "$stage/opt/dezirojoy/"
chmod 0755 "$stage/opt/dezirojoy/DeziroJoy"
cp "$icon" "$stage/opt/dezirojoy/dezirojoy.ico"

# The device-access fix helper, shipped executable but inert: it writes the opt-in
# udev rules only when the app runs it through pkexec on the user's explicit
# request. Shipping it is what keeps the one-click fix from degrading to manual
# commands on a .rpm install, and it registers nothing by itself - the package
# still contains no udev rules.
install -m 0755 "$helper" "$stage/opt/dezirojoy/fix-device-access.sh"

install -m 0644 "$desktop" "$stage/usr/share/applications/dezirojoy.desktop"

# The icon-theme payload: one PNG per hicolor size, installed as-is from the
# frames committed under Assets/. No tool is involved - the Ubuntu CI runners
# ship no ImageMagick, and unpacking the .ico at build time would have made the
# release .rpm depend on it. The loop is also the completeness check: a missing
# size fails the build here rather than shipping a package whose icons silently
# do not exist. Re-extract the frames (Assets/dezirojoy-<size>.png, byte-exact
# PNG entries of the .ico) whenever the icon is re-cut.
for size in 16 24 32 48 64 128 256; do
  frame="$repo_root/src/DeziroJoy.App/Assets/dezirojoy-$size.png"
  if [ ! -f "$frame" ]; then
    echo "icon theme source missing: $frame" >&2
    exit 1
  fi

  install -Dm644 "$frame" "$stage/usr/share/icons/hicolor/${size}x${size}/apps/dezirojoy.png"
done

# _topdir is explicit: the Debian rpm defaults to a different layout than
# Fedora's, and the build must behave the same wherever it runs.
mkdir -p "$topdir"/{BUILD,BUILDROOT,RPMS,SRPMS,SOURCES,SPECS}

# rpmbuild refuses a BuildArch the host's rpmrc does not list as
# build-compatible, and upstream ships no x86_64 -> aarch64 entry - but the
# arm64 release leg cross-builds on an x86_64 runner. The payload is a staged
# binary tree, nothing is compiled here, so the check only needs to be told
# this cross build is intended. Two pieces: one extra buildarch_compat line,
# read after the system rpmrc (widening the table instead of replacing it),
# and --target, whose config re-read is what rebuilds the compatibility table
# from the widened cache - without it the table stays the one built before
# the extra line was ever read.
rpmbuild_args=(-bb "$spec"
  --define "_topdir $topdir"
  --define "_stage $stage"
  --define "_version $rpm_version"
  --define "_arch $arch")
host_arch="$(rpm --eval '%{_target_cpu}')"
if [ "$host_arch" != "$arch" ]; then
  crossrc="$(mktemp)"
  trap 'rm -rf "$stage" "$topdir" "$crossrc"' EXIT
  printf 'buildarch_compat: %s: %s\n' "$host_arch" "$arch" > "$crossrc"
  rpmbuild_args+=(--target "$arch-linux"
    --rcfile "$(rpm --eval '%{_rpmconfigdir}')/rpmrc:$crossrc")
fi
rpmbuild "${rpmbuild_args[@]}"

# rpmbuild names its output after the full NEVRA
# (dezirojoy-<rpm version>-<release>.<arch>.rpm); the release asset keeps the
# original semver version and no release segment. The topdir is a fresh
# temporary directory, so exactly one rpm is built into it.
built="$(find "$topdir" -name 'dezirojoy-*.rpm' -print -quit)"
if [ -z "$built" ] || [ ! -s "$built" ]; then
  echo "no rpm produced under $topdir" >&2
  exit 1
fi

artifact="DeziroJoy-${version}-${arch}.rpm"
mv "$built" "$outdir/$artifact"

if [ ! -s "$outdir/$artifact" ]; then
  echo "no rpm produced at $outdir/$artifact" >&2
  exit 1
fi

echo "built $artifact"
rpm -qp --info "$outdir/$artifact"
