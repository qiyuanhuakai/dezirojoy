    };

    /// <summary>Keys that need KEYEVENTF_EXTENDEDKEY on Windows.</summary>
    public static bool IsExtendedKey(GamepadKey key) => key switch
    {
        GamepadKey.ArrowUp or GamepadKey.ArrowDown or GamepadKey.ArrowLeft or GamepadKey.ArrowRight
            or GamepadKey.Home or GamepadKey.End or GamepadKey.Insert or GamepadKey.Delete
            or GamepadKey.PageUp or GamepadKey.PageDown => true,
        _ => false,
    };
}
