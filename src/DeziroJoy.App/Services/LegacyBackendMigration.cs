using DeziroJoy.Core.Input;
using DeziroJoy.Core.Mapping;
using DeziroJoy.Core.Profiles;
using DeziroJoy.Platform.Sdl3;

namespace DeziroJoy.App.Services;

/// <summary>
/// What one migration pass did for one device: the slots it copied across, and every
/// reason it did not copy something. The notes are the diagnostic surface - a skipped
/// pairing says why, so a user with two pads is told the ambiguity instead of watching
/// one pad silently keep the other's configuration.
/// </summary>
public sealed record LegacyMigrationReport(
    string DeviceId,
    IReadOnlyList<int> CopiedSlots,
    IReadOnlyList<string> Notes)
{
    /// <summary>The legacy device the configuration came from, or null when nothing was paired.</summary>
    public string? LegacyDeviceId { get; init; }

    public bool Migrated => CopiedSlots.Count > 0;
}

/// <summary>
/// Copies a user's configuration from the backend they used before SDL3 onto the SDL
/// device that replaced it. The two backends key profiles by different device identities -
/// XInput by user index (<c>xinput:N</c>), evdev by device path (<c>/dev/input/eventN</c>),
/// SDL3 by <c>sdl:{guid}[:{serial}][:{path}]</c> - so switching backends has always left
/// the old configuration orphaned on disk while the new device materialized the library
/// defaults. This is the conservative bridge for that gap: the old files are never touched,
/// nothing is ever invented, and an ambiguous pairing does nothing rather than guessing.
/// <para>
/// The rules, in the order they are applied:
/// </para>
/// <list type="bullet">
/// <item>Only SDL devices are migrated onto; a non-SDL device is left entirely alone.</item>
/// <item>A pair the migration record shows as already processed is left alone - the first
/// run decided for it, and re-running would refill slots the user has since deleted or
/// replace a slot they reset to the defaults (see <see cref="ILegacyMigrationMarkers"/>).</item>
/// <item>Exactly one legacy device and one SDL device map onto each other. Anything larger
/// is skipped and named: neither identity says which SDL device is which physical pad, and
/// a runtime player index is an assignment, not an identity, so it is not evidence.</item>
/// <item>Even at one-to-one, a legacy configuration and an SDL device that both report a
/// specific but different layout are not the same controller, and the migration declines
/// rather than move one pad's configuration onto another.</item>
/// <item>A slot is copied only when the SDL device's slot of the same number is absent or
/// provably the untouched library default (see <see cref="MatchesAutoGenerated"/>). A slot
/// the user has already customized under SDL is never overwritten, which is what makes the
/// migration safe for someone who already started configuring the SDL device in an earlier
/// alpha.</item>
/// <item>Slot numbers are preserved verbatim, because a leader key names the two slots it
/// flips between and a gesture, layer or special key lives inside the copied body.</item>
/// <item>The legacy files are only ever read: the copy writes new keys beside them, so the
/// old configuration stays exactly where the old backend left it.</item>
/// </list>
/// </summary>
public sealed class LegacyBackendMigration
{
    /// <summary>The device-id prefix every SDL profile key carries.</summary>
    public const string SdlPrefix = Sdl3GamepadIdentity.DeviceIdPrefix;

    private const string XInputPrefix = "xinput:";

    private const string EvdevPrefix = "/dev/input/";

    private const string SlotKeyPrefix = "preset";

    private readonly ILegacyMigrationMarkers _markers;

    /// <summary>
    /// The store snapshot the legacy devices were discovered from, computed once per host.
    /// The engine calls the migration on every new device, and re-reading every profile
    /// inside the engine lock for a set that only changes when another backend session
    /// writes it is pure cost; a configuration that appears mid-session is picked up by the
    /// next daemon restart, which re-runs the discovery and says what it found.
    /// </summary>
    private IReadOnlyList<GamepadProfile>? _storeSnapshot;

    private List<LegacyDevice>? _legacyDevices;

    public LegacyBackendMigration(ILegacyMigrationMarkers? markers = null)
    {
        _markers = markers ?? new LegacyMigrationMarkerFile();
    }

    /// <summary>
    /// Runs the migration for one newly connected SDL device, with the full set of
    /// currently connected devices for the pairing decision. Returns the report when
    /// something was copied or something worth diagnosing was skipped, and null when there
    /// was nothing to do at all.
    /// </summary>
    public LegacyMigrationReport? Migrate(
        IProfileStore store,
        GamepadDescriptor descriptor,
        IReadOnlyList<GamepadDescriptor> connected)
    {
        ArgumentNullException.ThrowIfNull(store);
        ArgumentNullException.ThrowIfNull(descriptor);
        ArgumentNullException.ThrowIfNull(connected);

        if (!descriptor.DeviceId.StartsWith(SdlPrefix, StringComparison.Ordinal))
        {
            // XInput, evdev or a test pad: their own keys already hold their configuration.
            return null;
        }

        var markers = _markers.Load();
        if (markers is null)
        {
            // The record cannot be read, so no pair can be proven new. Declining everything
            // is the safe direction: a repeated migration would refill deleted slots and
            // replace reset ones, which is precisely what the record exists to prevent.
            return new LegacyMigrationReport(
                descriptor.DeviceId,
                [],
                ["旧配置迁移记录无法读取，本次未迁移（宁可跳过，不覆盖现有配置）。"]);
        }

        var legacyDevices = Discover(store);
        if (legacyDevices.Count == 0)
        {
            return null;
        }

        var notes = new List<string>();
        if (!TryPair(legacyDevices, descriptor, connected, out var legacy, notes))
        {
            if (legacy.DeviceId is null)
            {
                // No pair was determined at all: the counts made the choice impossible.
                return notes.Count > 0
                    ? new LegacyMigrationReport(descriptor.DeviceId, [], notes)
                    : null;
            }

            // A pair that was determined and then declined - the layouts clearly differ -
            // is processed too: the decision is recorded once, so a restart neither repeats
            // the diagnostic nor re-opens a question that was answered.
            var declined = new LegacyMigrationPair(legacy.DeviceId, descriptor.DeviceId);
            if (markers.Contains(declined))
            {
                return null;
            }

            _markers.Mark(declined);
            return new LegacyMigrationReport(descriptor.DeviceId, [], notes)
            {
                LegacyDeviceId = legacy.DeviceId,
            };
        }

        var pair = new LegacyMigrationPair(legacy.DeviceId, descriptor.DeviceId);
        if (markers.Contains(pair))
        {
            // Processed once already: a later run must not copy or backfill anything, or it
            // would undo the deletions and resets the user made since.
            return null;
        }

        var report = CopyAcross(store, descriptor, legacy, _storeSnapshot!, notes);
        _markers.Mark(pair);
        return report;
    }

    /// <summary>
    /// The legacy devices the store holds, discovered once per host from a single read of
    /// every profile. A device with no primary profile has no configuration to carry across
    /// and is not listed.
    /// </summary>
    private List<LegacyDevice> Discover(IProfileStore store)
    {
        if (_legacyDevices is not null)
        {
            return _legacyDevices;
        }

        _storeSnapshot = store.LoadAll();
        var ids = new SortedSet<string>(StringComparer.Ordinal);

        foreach (var profile in _storeSnapshot)
        {
            if (DeviceOfKey(profile.DeviceId) is { } device && IsLegacyDevice(device))
            {
                ids.Add(device);
            }
        }

        var devices = new List<LegacyDevice>();
        foreach (var id in ids)
        {
            if (PrimaryOf(id) is { } primary)
            {
                devices.Add(new LegacyDevice(id, primary.Layout));
            }
        }

        _legacyDevices = devices;
        return devices;
    }

    /// <summary>The primary (slot 1) profile one legacy device carries, or null when it has none.</summary>
    private GamepadProfile? PrimaryOf(string deviceId)
        => _storeSnapshot!.FirstOrDefault(profile => string.Equals(profile.DeviceId, deviceId, StringComparison.Ordinal));

    /// <summary>
    /// Pairs one SDL device with the legacy device its configuration should come from.
    /// Exactly one legacy device and one SDL device pair outright; anything larger is
    /// skipped with one note naming the counts, because neither identity says which pad is
    /// which, and no pair is determined at all. Even at one-to-one the pair is declined
    /// when both sides report a specific but different layout - the one case where the two
    /// clearly are not the same controller - but the pair is still named, so the caller can
    /// record that the question was answered once.
    /// </summary>
    private static bool TryPair(
        IReadOnlyList<LegacyDevice> legacyDevices,
        GamepadDescriptor descriptor,
        IReadOnlyList<GamepadDescriptor> connected,
        out LegacyDevice legacy,
        List<string> notes)
    {
        legacy = default;

        var sdlCount = connected.Count(device => device.DeviceId.StartsWith(SdlPrefix, StringComparison.Ordinal));

        if (legacyDevices.Count != 1 || sdlCount != 1)
        {
            notes.Add(
                $"旧后端配置共 {legacyDevices.Count} 个、当前连接了 {sdlCount} 个 SDL 设备，"
                + "无法可靠判断哪个配置属于哪个手柄，未迁移。");
            return false;
        }

        legacy = legacyDevices[0];
        if (LayoutsClearlyDiffer(legacy.Layout, descriptor.Layout))
        {
            notes.Add(
                $"旧后端配置 {legacy.DeviceId}（{DescribeLayout(legacy.Layout)}）"
                + $"与 SDL 设备 {descriptor.DeviceId}（{DescribeLayout(descriptor.Layout)}）"
                + "布局明确不同，不像同一只手柄，未迁移。");
            return false;
        }

        return true;
    }

    /// <summary>
    /// True when both sides name a specific layout and the two disagree. A generic layout on
    /// either side is an unknown, not a difference: the migration proceeds and the copied
    /// configuration is the best evidence available.
    /// </summary>
    private static bool LayoutsClearlyDiffer(GamepadLayout left, GamepadLayout right)
        => left != GamepadLayout.Generic
            && right != GamepadLayout.Generic
            && left != right;

    private static string DescribeLayout(GamepadLayout layout) => layout switch
    {
        GamepadLayout.Xbox => "Xbox 布局",
        GamepadLayout.DualShock => "DualShock 布局",
        _ => "通用布局",
    };

    /// <summary>
    /// Copies every slot of one legacy device onto one SDL device. A slot the SDL device
    /// already holds is copied only when it is provably the untouched library default; a
    /// customized SDL slot is kept and named instead. The legacy files are never touched -
    /// the copy writes new keys beside them, so the old configuration stays where the old
    /// backend left it.
    /// </summary>
    private static LegacyMigrationReport CopyAcross(
        IProfileStore store,
        GamepadDescriptor descriptor,
        LegacyDevice legacy,
        IReadOnlyList<GamepadProfile> profiles,
        List<string> notes)
    {
        var presets = new PresetStore(store);
        var copied = new List<int>();

        foreach (var slot in SlotsInUse(profiles, legacy.DeviceId))
        {
            if (SlotOf(profiles, legacy.DeviceId, slot) is not { } legacyProfile)
            {
                continue;
            }

            if (presets.LoadSlot(descriptor.DeviceId, slot) is { } existing
                && !MatchesAutoGenerated(existing, slot, descriptor.Layout))
            {
                // The user already configured this slot under SDL: their work wins, and the
                // legacy body for this slot is left on disk rather than copied over the top.
                notes.Add(
                    $"SDL 设备的预设 {slot} 已是自定义配置，保留未动；"
                    + $"旧后端 {legacy.DeviceId} 的同号预设未复制。");
                continue;
            }

            presets.SaveSlot(
                descriptor.DeviceId,
                slot,
                legacyProfile with
                {
                    DeviceId = PresetStore.KeyFor(descriptor.DeviceId, slot),
                    PresetSlot = slot,
                });
            copied.Add(slot);
        }

        if (copied.Count == 0)
        {
            notes.Add($"旧后端配置 {legacy.DeviceId} 没有可复制的预设槽。");
            return new LegacyMigrationReport(descriptor.DeviceId, [], notes) { LegacyDeviceId = legacy.DeviceId };
        }

        notes.Insert(0, $"已将旧后端 {legacy.DeviceId} 的预设 {string.Join("、", copied)} 复制到 SDL 设备（原文件保留）。");
        return new LegacyMigrationReport(descriptor.DeviceId, copied, notes) { LegacyDeviceId = legacy.DeviceId };
    }

    /// <summary>
    /// Whether one stored profile is exactly what <see cref="PresetStore.EnsureDefaults"/>
    /// would have materialized for this device and slot - the proof that replacing it loses
    /// nothing the user made. Compared field by field against the library default, with the
    /// one exception of the mapping entry ids: the library mints a fresh GUID per entry on
    /// every generation, so two untouched defaults never share ids and comparing them would
    /// make every auto-generated slot look custom. Everything else - the layout, the name
    /// EnsureDefaults derives, the mapping list with its sources, targets, gestures, layers
    /// and enabled flags - must match exactly.
    /// <para>
    /// The slot tag is accepted in either of the two shapes an untouched default appears in:
    /// the stored copy keeps the primary's slot 1, and the running profile is tagged with the
    /// slot it actually loaded. Both are the default; only the bookkeeping differs.
    /// </para>
    /// </summary>
    public static bool MatchesAutoGenerated(GamepadProfile profile, int slot, GamepadLayout layout)
    {
        ArgumentNullException.ThrowIfNull(profile);

        var expected = DefaultProfileLibrary.CreateForLayout(layout);
        var expectedName = slot <= PresetStore.MinSlot
            ? expected.Name
            : $"{expected.Name} · 预设 {slot}";

        return profile.Layout == layout
            && profile.Name == expectedName
            && (profile.PresetSlot == PresetStore.MinSlot || profile.PresetSlot == slot)
            && MappingsMatch(profile.Mappings, expected.Mappings);
    }

    /// <summary>
    /// Field-by-field comparison of two mapping lists, entry ids aside: the same sources,
    /// targets, enabled flags and layers in the same order. Gestures, complex shortcuts and
    /// special keys live inside the source and target records, so a gesture or a DSL program
    /// that differs makes the lists differ.
    /// </summary>
    private static bool MappingsMatch(
        IReadOnlyList<MappingEntry> left,
        IReadOnlyList<MappingEntry> right)
    {
        if (left.Count != right.Count)
        {
            return false;
        }

        for (var index = 0; index < left.Count; index++)
        {
            var a = left[index];
            var b = right[index];

            if (a.Source != b.Source || a.Target != b.Target || a.Enabled != b.Enabled || a.Layer != b.Layer)
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>
    /// The slots one device holds, read from the snapshot the discovery already took: the
    /// bare device id for slot 1, the id after the slot prefix for every later slot.
    /// </summary>
    private static IReadOnlyList<int> SlotsInUse(IReadOnlyList<GamepadProfile> profiles, string deviceId)
    {
        var slots = new SortedSet<int>();

        foreach (var profile in profiles)
        {
            if (SlotFromKey(profile.DeviceId, deviceId) is { } slot)
            {
                slots.Add(slot);
            }
        }

        return [.. slots];
    }

    /// <summary>The profile one device holds in one slot, from the same snapshot.</summary>
    private static GamepadProfile? SlotOf(IReadOnlyList<GamepadProfile> profiles, string deviceId, int slot)
        => profiles.FirstOrDefault(profile => SlotFromKey(profile.DeviceId, deviceId) == slot);

    /// <summary>
    /// The device a stored key belongs to: the bare device id for slot 1, the id after the
    /// slot prefix for every later slot. A key with no recognizable shape - a name-based key
    /// from before device ids existed, say - is not a device this migration understands.
    /// </summary>
    private static string? DeviceOfKey(string? key)
    {
        if (string.IsNullOrEmpty(key))
        {
            return null;
        }

        if (!key.StartsWith(SlotKeyPrefix, StringComparison.Ordinal))
        {
            return key;
        }

        var rest = key[SlotKeyPrefix.Length..];
        var colon = rest.IndexOf(':');

        return colon > 0 && int.TryParse(rest.AsSpan(0, colon), out _)
            ? rest[(colon + 1)..]
            : key;
    }

    /// <summary>
    /// The slot number a stored key stands for, or null when it is not one of this device's
    /// slots. The device id - which may itself contain a colon, as XInput ids do - is
    /// matched as the suffix after the slot number.
    /// </summary>
    private static int? SlotFromKey(string? key, string deviceId)
    {
        if (string.IsNullOrEmpty(key))
        {
            return null;
        }

        if (string.Equals(key, deviceId, StringComparison.Ordinal))
        {
            return PresetStore.MinSlot;
        }

        if (!key.StartsWith(SlotKeyPrefix, StringComparison.Ordinal))
        {
            return null;
        }

        var rest = key[SlotKeyPrefix.Length..];
        var colon = rest.IndexOf(':');
        if (colon <= 0)
        {
            return null;
        }

        return int.TryParse(rest.AsSpan(0, colon), out var slot)
            && slot > PresetStore.MinSlot
            && string.Equals(rest[(colon + 1)..], deviceId, StringComparison.Ordinal)
                ? slot
                : null;
    }

    /// <summary>
    /// Whether one device id belongs to a backend this migration understands: XInput's
    /// <c>xinput:N</c> or evdev's <c>/dev/input/...</c> path. Anything else - an SDL id, a
    /// performance-baseline pad, a hand-made key - is left alone rather than guessed at.
    /// </summary>
    private static bool IsLegacyDevice(string deviceId)
        => deviceId.StartsWith(XInputPrefix, StringComparison.Ordinal)
            || deviceId.StartsWith(EvdevPrefix, StringComparison.Ordinal);

    private readonly record struct LegacyDevice(string DeviceId, GamepadLayout Layout);
}
